export function resolveLocale(languages = globalThis.navigator?.languages, language = globalThis.navigator?.language) {
  const preferred = languages?.[0] || language || "en";
  return /^zh(?:-|$)/i.test(preferred) ? "zh-CN" : "en";
}

export function translate(message, values = [], locale = resolveLocale()) {
  const text = locale === "zh-CN" && Object.hasOwn(chinese, message) ? chinese[message] : message;
  return text.replace(/\{(\d+)\}/g, (placeholder, index) => index < values.length ? String(values[index]) : placeholder);
}

// Tagged templates keep dynamic content out of the dictionary and preserve it verbatim.
export function t(message, ...values) {
  const key = Array.isArray(message)
    ? message.map((part, index) => part + (index < values.length ? `{${index}}` : "")).join("")
    : message;
  return translate(key, values);
}

export function localizeDocument(document, locale = resolveLocale()) {
  if (document.documentElement) document.documentElement.lang = locale;
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = translate(element.dataset.i18n, [], locale);
  }
  for (const attribute of ["placeholder", "aria-label"]) {
    const key = attribute === "aria-label" ? "i18nAriaLabel" : "i18nPlaceholder";
    for (const element of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, translate(element.dataset[key], [], locale));
    }
  }
}
